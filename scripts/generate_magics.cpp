// Regenerate native/magic_numbers.h with --output PATH. No network or chess library.
#include "../native/slider_geometry.h"
#include <bit>
#include <fstream>
#include <iostream>
#include <random>
#include <stdexcept>
#include <string>
#include <vector>

using namespace mero_sliders;
U64 find_magic(int kind, int sq, std::mt19937_64& rng) {
    U64 mask = trace(kind, sq, 0, true);
    int shift = 64 - std::popcount(mask);
    unsigned n = 1u << (64-shift);
    std::vector<U64> occ, attack, values(n);
    std::vector<unsigned> used(n);
    U64 subset = 0;
    do {
        occ.push_back(subset);
        attack.push_back(trace(kind,sq,subset));
        subset = (subset-mask)&mask;
    } while (subset);
    for (unsigned generation = 1; generation; ++generation) {
        U64 candidate = rng();
        candidate &= rng();
        candidate &= rng();
        if (std::popcount((mask*candidate) >> 56) < 6) continue;
        unsigned i = 0;
        for (; i < n; ++i) {
            auto idx = (occ[i]*candidate) >> shift;
            if (used[idx] == generation && values[idx] != attack[i]) break;
            used[idx] = generation;
            values[idx] = attack[i];
        }
        if (i == n) return candidate;
    }
    throw std::runtime_error("magic search exhausted");
}

int main(int argc, char** argv) {
    if (argc != 3 || std::string(argv[1]) != "--output") return 2;
    std::ofstream out(argv[2]);
    if (!out) return 1;
    out << "// Generated by scripts/generate_magics.cpp; Mero square 0 is a8.\n"
        << "#pragma once\n#include <cstdint>\nnamespace mero_sliders {\n"
        << "inline constexpr std::uint64_t factors[2][64] = {\n";
    std::mt19937_64 rng(0x4d65726f);
    for (int kind = 0; kind < 2; ++kind) {
        out << "{\n";
        for (int sq = 0; sq < 64; ++sq)
            out << "0x" << std::hex << find_magic(kind,sq,rng) << "ULL,"
                << ((sq%4 == 3) ? "\n" : " ");
        out << "},\n";
    }
    out << "};\n}\n";
    return out.flush() ? 0 : 1;
}
