import argparse
from pathlib import Path
import torch
from .model import MeroNet
from .quantize import quantize, INPUT_SCALE, OUTPUT_SCALE

def header(model):
    rows, bias, head = quantize(model)
    def vector(values):
        return "{" + ",".join(str(v) for v in values) + "}"
    features = ",\n".join(vector(row) for row in rows)
    return f"""// Generated by python -m training.export from Mero's trained checkpoint.
#pragma once
#include <cstdint>
namespace mero_weights {{
inline constexpr int width = {len(head)};
inline constexpr int input_scale = {INPUT_SCALE};
inline constexpr int output_scale = {OUTPUT_SCALE};
alignas(64) inline constexpr std::int16_t features[768][width] = {{
{features}
}};
inline constexpr std::int16_t bias[width] = {vector(bias)};
inline constexpr std::int16_t head[width] = {vector(head)};
}}
"""

def load_model(checkpoint):
    data = torch.load(checkpoint, map_location="cpu", weights_only=True)
    model = MeroNet(data["width"])
    model.load_state_dict(data["state"])
    return model.eval()

def main():
    p = argparse.ArgumentParser()
    p.add_argument("checkpoint", type=Path)
    p.add_argument("header", type=Path)
    args = p.parse_args()
    args.header.write_text(header(load_model(args.checkpoint)))

if __name__ == "__main__":
    main()
